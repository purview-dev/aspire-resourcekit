using Purview.Aspire.ResourceKit.SourceGeneration.Helpers;
using Purview.Aspire.ResourceKit.SourceGeneration.Models;

namespace Purview.Aspire.ResourceKit.SourceGeneration;

partial class HostKitGenerator
{
	static string BuildSource(HostKitInfo hostKitInfo, GenerationContext context, CancellationToken cancellationToken)
	{
		CodeWriter writer = new();

		writer
			.WriteLine("// <auto-generated />")
			.NewLine()
			.WriteLine("#nullable enable")
			.NewLine()
			.WriteLine("using global::Microsoft.Extensions.Configuration;")
			.WriteLine("using global::Microsoft.Extensions.DependencyInjection;")
			.WriteLine("using global::Microsoft.Extensions.Options;")
			.WriteLine("using global::System;")
			.NewLine();

		cancellationToken.ThrowIfCancellationRequested();

		BuildHostKit(writer, hostKitInfo, context, cancellationToken);
		BuildResourceKits(writer, hostKitInfo, context, cancellationToken);
		BuildExtensionMethod(writer, hostKitInfo, context, cancellationToken);

		return SourceGenHelpers.AddCodeGen(writer.ToString());
	}
}
